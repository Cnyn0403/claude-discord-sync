export const LANGUAGES = { en, 'zh-TW': zhTW, 'zh-CN': zhCN } as const satisfies Record<string, Messages>
export type Language = keyof typeof LANGUAGES

/** The active locale. Set once at startup by loadConfig(); a live binding for importers. */
export let m: Messages = en

/** The language a config value names, or English if it names none. Unlike setLanguage() it leaves `m` alone. */
export function pickLanguage(lang: string | undefined): Language {
  return (lang && lang in LANGUAGES ? lang : 'en') as Language
}

export function setLanguage(lang: string | undefined): Language {
  const key = pickLanguage(lang)
  m = LANGUAGES[key]
  return key
}

